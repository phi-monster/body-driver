use battery::*;
use contact_set::Twist;

fn main() {
    for (名, cloud, z, hand) in [
        ("圆锥", 圆锥(0.035, 0.09, 0.90), 0.93, Hand::双臂),
        ("圆柱", 圆柱(0.03, 0.08, 0.90), 0.94, Hand::吸盘),
        ("薄板", 薄板(0.10, 0.08, 0.004, 0.90), 0.94, Hand::三指),
        ("薄板", 薄板(0.10, 0.08, 0.004, 0.90), 0.94, Hand::五指),
    ] {
        println!("═══ {名} / {} ═══", hand.名());
        print!("{}", 看一格(&cloud, hand, z));
        let 心 = [0.0, 0.0, z];
        for (什么, m) in [
            ("平移+x", Twist::slide([0.05, 0.0, 0.0])),
            ("平移+y", Twist::slide([0.0, 0.05, 0.0])),
            ("平移+z", Twist::slide([0.0, 0.0, 0.05])),
            ("绕x转", Twist::turn([1.0, 0.0, 0.0], 0.5, 心).unwrap()),
            ("绕y转", Twist::turn([0.0, 1.0, 0.0], 0.5, 心).unwrap()),
            ("绕z转", Twist::turn([0.0, 0.0, 1.0], 0.5, 心).unwrap()),
        ] {
            println!("  {什么}: {}", if 试(&cloud, hand, z, m) { "行" } else { "不行" });
        }
    }
}
