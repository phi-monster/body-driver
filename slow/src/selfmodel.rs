//! **身体不是一张数表,是一张因果表。**
//!
//! 这一层回答的是同一个问题的两个主语:
//!
//! ```text
//! 我发这个命令 ⇒ 世界上【这一块】这样动     ← 主语是「我」 ⇒ 身体
//! 我压 / 合 / 抬 ⇒ 【它】这样反应            ← 主语是「它」 ⇒ 物体
//! ```
//!
//! 而「我」和「不是我」这条界**不需要谁来标注,它从因果里自己掉出来**:
//! **只在我命令时才动的是我;我推它才动、而且有自己脾气的是世界。**
//!
//! # 为什么要有这个文件(病历,不是理念)
//!
//! 在它之前,身体知识是 **15 个各自独立的标量**,每个自己一条探针、自己一套判据、
//! 自己存一份。代价是仓里最贵的两类 bug,而**两类都不是"量得不够准"**:
//!
//! **① 互相不自洽,而两边日志都正常。** 同一具身体的两件事在两处各写一份,谁也不用
//!    对谁负责,于是"一个完全正常的错数"能一路走到底:
//!    - 工具轴那一列两边**约定不一样** ⇒ 爪子歪 90°,而两侧日志全绿
//!    - 爪宽从第 1 台相机读、尺是第 0 台的 ⇒ 除得出一个像模像样的宽度,而它是错的
//!    - 相机约定 `−z 朝前` 当成 `+z 朝前` ⇒ 整个三维重建**上下颠倒**
//!      (桌面法向读成 `[0.44,0.21,0.87]` —— 偏离竖直 29.5°,恰好是相机自己的俯仰)
//!    - 走位命令吃**法兰**、接触集给**工具尖** ⇒ 差 0.1451 m,不换算就整段不动
//!
//! **② 不可复现。** 15 次从零标定:一炮拿到 4–10 格;**跨 15 炮散布 <2% 的只有 1 格**。
//!    接触阈 **1603%** · 原位 **1954%** · 手眼 **564%** · 臂重 **238%**。
//!    根子是**每个量各拟各的**:几十条观测拟一个数,约束太少。
//!
//! ⇒ 这一层把它们换成**一个对象**:所有观测必须**同时**解释它。
//! 对不上的观测以**残差**的形式当场露出来,而不是安安静静给出一个看起来正常的错数。
//! 而"第几列是工具轴"这类问题**根本不再存在** —— 模型里没有约定,只有量出来的方向。
//!
//! # 怎么建(就是这一层一直在用的那条构造性身份)
//!
//! **别的全冻住,只动一个通道 ⇒ 画面里会动的那一块,【按构造】就是这个通道管的部件。**
//! 这条 2026-08-10 / 08-14 两次验通,而且它比"问 VLM 哪个是你的手"硬得多 ——
//! VLM 会指到手肘和底座上(档案里的"幻影病"),而构造性身份**指不错**:
//! 一个不听我命令的东西,不会在我下命令的那一拍跟着动。
//!
//! 它同时是**镜子测试的那条机制**(contingency):我一动,那个东西跟着动 ⇒ 那是我。
//! 差别只在于:动物把它连到一个留得住的身体像上,而这一层此前**动作一停自我就没了**。
//! 这个文件就是那个留得住的部分。
//!
//! # 🔴 它【不】负责的事(不许含糊)
//!
//! - **这东西多重 / 多滑 / 会不会掉** —— 那是世界的属性,只能碰一下量(主语是「它」)。
//!   同一套机器,不同的主语;但那一半不在这个 struct 里。
//! - **哪个物体 / 抓哪儿有用** —— 语义,永远归上面那一层。
//! - **形状要看得见才建得起来** —— 一台俯视相机只看得见顶面,点云是一张平面
//!   (实测跨度 0.0000 m ⇒ 接触生成器判 `Flat`)。**换个角度再看一眼**就够,而
//!   "两只普通相机"那条路本来就是架构底线。

use crate::measurement::Quantity;

/// 一个**通道**:一条能下命令的自由度。两指爪 = 1 个指通道,五指手 = 5 个,
/// 吸盘 = 1 个,七轴臂 = 7 个关节通道。**数量由布局发现给,这一层不假设。**
#[derive(Copy, Clone, PartialEq, Eq, Debug)]
pub enum 通道 {
    /// 第 `i` 个关节。
    关节(usize),
    /// 第 `i` 个指通道(`Cmd::Grip` 的第 i 路)。
    指(usize),
}

/// 一次**抖动**留下的证据:动这一个通道,画面里哪一块跟着动了。
///
/// 🔴 三个数一起才有意义,分开任何一个都能骗人:
/// - `动了多少像素` 小 ⇒ 这一档根本没看见(激励太小 / 被自己挡住 / 时序错位)
/// - `命令` 与 `实到` 差得远 ⇒ 这一档**没走到位**,而"没走到位"和"走到了但看不见"
///   在像素上完全同形(交付率低的身体上尤其如此:命令 +0.2 rad 实到 +0.005)
#[derive(Clone, Debug)]
pub struct 一抖 {
    /// 动的是哪个通道。
    pub 通道: 通道,
    /// 命令它走多少(该通道自己的单位:关节是弧度,指通道是无量纲开度)。
    pub 命令: f64,
    /// 它**实际**走了多少(本体感受读的)。
    pub 实到: f64,
    /// 这一抖在第 `相机` 台相机上让多少像素越过了噪声地板。
    pub 相机: usize,
    /// 越过地板的像素数。
    pub 动了多少像素: u32,
    /// 那一块的**包围盒**(归一化画幅 `[umin,vmin,umax,vmax]`)。
    pub 盒: [f64; 4],
    /// 那一块的形心(归一化画幅)。
    pub 形心: (f64, f64),
    /// 那一块反投影出来的三维点里,**离基准点最远**的那一个(世界系,米)。
    /// 基准点 = 下命令时机体自报的末端位置。指通道上,这就是**指尖**。
    pub 最远点: Option<[f64; 3]>,
    /// 上一行那个距离。
    pub 最远多远: f64,
    /// 量这一抖时的噪声地板(那台相机自己的)。地板是判据的一部分,不是背景信息。
    pub 地板: u8,
}

impl 一抖 {
    /// 这一抖**算不算数**。
    ///
    /// 🔴 判据只有两条,都不带身体常数:
    /// ① **真的走到了** —— 实到与命令同号,且至少走掉命令的十分之一。
    ///    (十分之一是**协议选择**:比这更小的一步,像素上和不动分不开。)
    /// ② **真的看见了** —— 越过地板的像素数比地板本身给得出的还多。
    ///
    /// ⚠️ 不判"动得像不像一个刚体"—— 那要三帧,不是这一层的活(见 `crate::blob`)。
    pub fn 算数(&self) -> bool {
        let 走到了 = self.实到 * self.命令 > 0.0 && self.实到.abs() >= self.命令.abs() / 10.0;
        走到了 && self.动了多少像素 > u32::from(self.地板).max(1)
    }
}

/// **一具身体:通道 ⇒ 它管着哪一块。**
///
/// 这不是"15 个量"的容器,是那 15 个量里**几何那一半的来源**。
#[derive(Clone, Debug, Default)]
pub struct 自模 {
    /// 攒下来的所有抖动证据。**原料不许扔** —— 扔了就退回"一个量拟一次"的老病。
    pub 证据: Vec<一抖>,
}

impl 自模 {
    /// 空的。
    pub fn new() -> Self {
        Self { 证据: Vec::new() }
    }

    /// 收一条证据。不算数的**照收不误**,只是不进推导 ——
    /// 🔴 "这一抖没算数"本身是要能被读出来的:一个从来没算数过的通道,
    /// 和一个从来没被抖过的通道,要改的东西完全不同。
    pub fn 收(&mut self, e: 一抖) {
        self.证据.push(e);
    }

    /// 这个通道有几条算数的证据。
    pub fn 算数几条(&self, c: 通道) -> usize {
        self.证据.iter().filter(|e| e.通道 == c && e.算数()).count()
    }

    /// 见过哪些通道(不管算不算数)。
    pub fn 见过的通道(&self) -> Vec<通道> {
        let mut v: Vec<通道> = Vec::new();
        for e in &self.证据 {
            if !v.contains(&e.通道) {
                v.push(e.通道);
            }
        }
        v
    }

    /// **法兰到指尖有多长** —— 从模型里读,不再单独量。
    ///
    /// 指通道管着的那一块里,离末端最远的那个三维点就是指尖;它到末端的距离就是这个数。
    /// 取所有算数证据的**中位数**(不是均值 —— 认错一次就能把均值拽走)。
    ///
    /// 🔴 为什么这样比原来那条探针强:原来是"绕垂直于工具轴的那一列转,弧半径就是它",
    /// 而那条**先得知道哪一列是工具轴**,于是两个未知数互相咬;实测在 Franka 上给到
    /// 30 个循环、弧点稳定产出,估计器仍判 **0.0001 m**(读成"这具身体没有工具")。
    /// 这里一个约定都不需要:**会动的那一块的远端**,没有第二种解释。
    pub fn 工具长(&self) -> Option<f64> {
        let mut v: Vec<f64> = self
            .证据
            .iter()
            .filter(|e| matches!(e.通道, 通道::指(_)) && e.算数() && e.最远点.is_some())
            .map(|e| e.最远多远)
            .filter(|d| d.is_finite() && *d > 0.0)
            .collect();
        if v.is_empty() {
            return None;
        }
        v.sort_by(|a, b| a.partial_cmp(b).unwrap());
        Some(v[v.len() / 2])
    }

    /// **钳口往哪个方向张开**(归一化画幅里的方向)—— 从模型里读。
    ///
    /// 指通道一动,那一块的包围盒会沿**开合那一维**长出去;取它长边的方向。
    /// 🔴 这里**没有"第几列"这个问题**:方向是量出来的,不是从旋转阵里挑一列挑出来的。
    /// 那个"挑列"正是仓里那条 bug 的形状——两边约定不一样 ⇒ 爪子歪 90° 而日志全绿。
    pub fn 开合方向(&self) -> Option<(f64, f64)> {
        let e = self
            .证据
            .iter()
            .filter(|e| matches!(e.通道, 通道::指(_)) && e.算数())
            .max_by_key(|e| e.动了多少像素)?;
        let (w, h) = (e.盒[2] - e.盒[0], e.盒[3] - e.盒[1]);
        if !(w.is_finite() && h.is_finite()) || (w <= 0.0 && h <= 0.0) {
            return None;
        }
        Some(if w >= h { (1.0, 0.0) } else { (0.0, 1.0) })
    }

    /// **这一格,模型答得上吗。** 答不上就是答不上 —— 这一层不编数。
    ///
    /// ⚠️ 只回答**几何那一类**。延迟 / 交付率 / 接触阈这些是**时间与力**的量,
    /// 它们不在这张因果表的形状里,仍旧各有各的探针。
    pub fn 答得上(&self, q: Quantity) -> bool {
        match q {
            Quantity::ToolOffset => self.工具长().is_some(),
            Quantity::GripperSpan => self.开合方向().is_some(),
            _ => false,
        }
    }
}

#[cfg(test)]
mod 测 {
    use super::*;

    fn 抖(c: 通道, 命令: f64, 实到: f64, px: u32, 盒: [f64; 4], 远: f64) -> 一抖 {
        一抖 {
            通道: c,
            命令,
            实到,
            相机: 0,
            动了多少像素: px,
            盒,
            形心: ((盒[0] + 盒[2]) / 2.0, (盒[1] + 盒[3]) / 2.0),
            最远点: Some([0.0, 0.0, -远]),
            最远多远: 远,
            地板: 7,
        }
    }

    /// 🔴 **没走到位的那一抖不许算数** —— 这正是第一版栽的地方:
    /// 命令 +0.2 rad 实到 +0.005(2.6%),七根关节全这样,而画面里什么都没变。
    #[test]
    fn 没走到位不算数() {
        let e = 抖(通道::关节(0), 0.2, 0.005, 9000, [0.1, 0.1, 0.3, 0.3], 0.1);
        assert!(!e.算数(), "只走掉 2.6% 的一抖必须被判不算数");
        let e2 = 抖(通道::关节(0), 0.2, 0.15, 9000, [0.1, 0.1, 0.3, 0.3], 0.1);
        assert!(e2.算数());
    }

    /// 走反了也不算数 —— 同号是判据的一半。
    #[test]
    fn 走反了不算数() {
        let e = 抖(通道::关节(1), 0.2, -0.18, 9000, [0.1, 0.1, 0.3, 0.3], 0.1);
        assert!(!e.算数());
    }

    /// 🔴 **动了但没看见**(像素没越过地板)也不算数 —— 与"没动"要分得开。
    #[test]
    fn 没看见不算数() {
        let e = 抖(通道::指(0), 1.0, 0.9, 3, [0.1, 0.1, 0.3, 0.3], 0.1);
        assert!(!e.算数(), "越过地板的像素比地板本身还少,不能算看见了");
    }

    /// 工具长取中位数,不取均值:认错一次不该把结果拽走。
    #[test]
    fn 工具长取中位不取均值() {
        let mut m = 自模::new();
        for 远 in [0.104, 0.106, 0.108, 0.110, 9.9] {
            m.收(抖(通道::指(0), 1.0, 0.9, 5000, [0.4, 0.4, 0.5, 0.45], 远));
        }
        let d = m.工具长().unwrap();
        assert!((0.10..0.12).contains(&d), "中位数该落在 0.10-0.12,拿到 {d}");
    }

    /// 一条算数证据都没有 ⇒ 答不上,而不是给个数。
    #[test]
    fn 没证据就答不上() {
        let mut m = 自模::new();
        m.收(抖(通道::指(0), 1.0, 0.02, 5000, [0.4, 0.4, 0.5, 0.45], 0.1));
        assert!(m.工具长().is_none());
        assert!(!m.答得上(Quantity::ToolOffset));
    }

    /// 开合方向取包围盒的长边 —— 横着张开就是横的,竖着就是竖的。
    #[test]
    fn 开合方向跟着盒子的长边() {
        let mut m = 自模::new();
        m.收(抖(通道::指(0), 1.0, 0.9, 5000, [0.30, 0.40, 0.50, 0.44], 0.1));
        assert_eq!(m.开合方向(), Some((1.0, 0.0)));
        let mut m2 = 自模::new();
        m2.收(抖(通道::指(0), 1.0, 0.9, 5000, [0.40, 0.30, 0.44, 0.50], 0.1));
        assert_eq!(m2.开合方向(), Some((0.0, 1.0)));
    }

    /// 不算数的证据照收,但不进推导 ——「没抖过」和「抖了不算数」要分得开。
    #[test]
    fn 不算数的照收但不进推导() {
        let mut m = 自模::new();
        m.收(抖(通道::指(0), 1.0, 0.02, 5000, [0.4, 0.4, 0.5, 0.45], 0.1));
        assert_eq!(m.见过的通道(), vec![通道::指(0)]);
        assert_eq!(m.算数几条(通道::指(0)), 0);
        assert!(m.工具长().is_none());
    }
}
