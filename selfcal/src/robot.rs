//! **一台机器人,在自标定眼里只有六件事。**
//!
//! 🔴 这一层存在的全部理由:上电自标定**从前是焊在一个 benchmark 的 Python 栈上的**
//! (`import uni_exec_deploy / uni_contract / bl_body / rd_verdict`),于是"换一具真机零重训"
//! 这句话在采样那一半根本不成立 —— 估计器可移植,而喂它的东西不可移植。
//! 拆开之后那四个模块里真正被用到的只有**两个线缆函数**,其余是纯数学、重复实现,
//! 或者是那个 benchmark 自己的计分挡板。
//!
//! # 🔴 允许 / 不允许(与探针那一侧同一条界)
//!
//! * **允许**:命令这具身体,读回**它自己**报的东西 —— 关节角、末端位姿、夹爪开度、自己的相机帧。
//!   一台真机的总线上这些全都有。
//! * **不允许**:从仿真器 / URDF / 相机矩阵里读一个几何常数。**那正是这一层要拦住的东西。**
//!
//! # 为什么传输不在这儿
//!
//! 驱动树是零依赖的(将来要跑在没有分配器故事的目标上),而一次 WebSocket 握手要
//! SHA-1 + base64。⇒ **动作程序在这儿,插头在外面。** 换一种机器人 = 换一个 `Robot` 实现,
//! 这个文件和整套相位程序一个字都不用改。

/// 这具身体报给自己的一帧。**全部是它自己的读数,没有一个来自世界。**
#[derive(Clone, Debug, Default)]
pub struct Frame {
    /// 每条臂的关节角(弧度)。条数由这具身体自己决定,不写死。
    pub joints: Vec<Vec<f64>>,
    /// 每条臂的末端位姿 `[x,y,z, qw,qx,qy,qz]`。
    pub ee: Vec<[f64; 7]>,
    /// 每条臂的夹爪开度回读(归一化)。
    pub jaw: Vec<f64>,
    /// 这具身体自己的相机图:`(宽, 高, RGB8)`。可以有零台或多台。
    pub cams: Vec<(usize, usize, Vec<u8>)>,
}

/// 命令这具身体做一件事。**只有它自己的量。**
#[derive(Clone, Debug)]
pub enum Cmd {
    /// 把第 `arm` 条臂的末端送到这个位姿,夹爪开到 `jaw`。
    Ee { arm: usize, at: [f64; 3], quat: [f64; 4], jaw: f64 },
    /// 把第 `arm` 条臂的末端送到这个位姿,**每个指通道各自**开到 `per[i]`。
    /// 这是手接口的最终形态:两爪 = 1 通道,五指手 = N 通道,吸盘 = 1 通道 ——
    /// 通道数由布局发现给,驱动不假设。`Ee.jaw`(标量)= 全通道广播的简写,
    /// 对"整只手一起开合"(power grasp)通用;单指动作(扣扳机)用这条。
    Grip { arm: usize, at: [f64; 3], quat: [f64; 4], per: Vec<f64> },
    /// 直接给关节角 —— 有些相位(齿隙、延迟)必须绕开逆解,否则量到的是求解器不是身体。
    Joints { arm: usize, q: Vec<f64>, jaw: f64 },
    /// 什么都不做,让它落定。
    Hold,
}

/// 插头。**六件事,一台真机的 SDK 全都有。**
pub trait Robot {
    /// 读一帧它自己报的东西。
    fn sense(&mut self) -> Option<Frame>;
    /// 发一条命令;返回是否发出去了(发不出去和"发了没动"是两件事,后者由采样看出来)。
    fn act(&mut self, c: &Cmd) -> bool;
    /// 关节名和限位 —— **只用来算身份指纹,不用来算几何**。一台真控制器两样都报。
    fn identity(&mut self) -> Vec<(String, f64, f64)>;
    /// 有几条臂。
    fn arms(&mut self) -> usize {
        self.sense().map(|f| f.joints.len()).unwrap_or(0)
    }
}
