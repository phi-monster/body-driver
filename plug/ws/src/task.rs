        let p = [j[1], -j[0], 0.0];
        let ph = p[0] * h[0] + p[1] * h[1];
        // 🔴🔴 **在够得着的候选里,挑【离身体最近】的那个。**
        // 实测(2026-08-17 夜):够不着是这条链现在唯一的阻塞,而它每次只差几厘米
        // (23/39/47 mm)。同一个物体上的候选彼此相差可达几厘米 —— **挑近的那个
        // 正好买到这个量级**。
        // ⚠️ 这不是档案判死的"改下手点排序"(那次是**强制固定序号**:候选 1 = 7 赢 25 输、
        // 候选 3 = 0 赢 57 输)。这里用的是 `DRIVER_GOAL:140` 明写认可的那条:
