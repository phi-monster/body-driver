        // 0.6 = 倾的收益系数下限(cos 夹角,无量纲)—— 低于它,倾了也退不了多少。
        // 倾腕补偿已死(补不动一律竖腕)⇒ 那个 0.6 的"倾的收益"门槛只剩害处:
        // 它会把收益低但【更近】的候选筛掉(N7 实锤:选中的候选离手 1.465 m)。
        // 选点只按"离手最近"。
        // 🔴🔴🔴 **排序用生成器自己量出来的那几个数,不用"离手最近"。**
        //
        // "离手最近"是我(仓)拍的,**和好不好夹毫无关系** —— 它只是"够得着"的一个粗糙替身。
