/// 不压缩的 24 位 BMP —— 渲图自证用。没有编码器,就没有"编码器悄悄改了图"这种查不出的偏差。
pub fn bmp24(rgb: &[u8], w: usize, h: usize) -> Vec<u8> {
    let row = (w * 3 + 3) & !3;
    let sz = 54 + row * h;
    let mut b = Vec::with_capacity(sz);
    b.extend_from_slice(b"BM");
    b.extend_from_slice(&(sz as u32).to_le_bytes());
    b.extend_from_slice(&[0; 4]);
    b.extend_from_slice(&54u32.to_le_bytes());
    b.extend_from_slice(&40u32.to_le_bytes());
    b.extend_from_slice(&(w as i32).to_le_bytes());
    b.extend_from_slice(&(h as i32).to_le_bytes());
    b.extend_from_slice(&1u16.to_le_bytes());
    b.extend_from_slice(&24u16.to_le_bytes());
    b.extend_from_slice(&[0; 24]);
    for y in (0..h).rev() {
        for x in 0..w {
            let i = (y * w + x) * 3;
            b.extend_from_slice(&[rgb[i + 2], rgb[i + 1], rgb[i]]);
        }
        for _ in 0..(row - w * 3) {
            b.push(0);
        }
    }
    b
}
