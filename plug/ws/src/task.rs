//! **任务这一格:真图 → 三维点 → 抓取候选 → 航点。这是驱动自己的,不是胶水。**
//!
//! 出身:`link/src/grasp.rs`(2026-08-19 整体迁入后删除)。迁入时改了三件事,每件都是
//! 那层胶水的病:
//! ① **删掉 `POSE24`** —— 216 个写死的数,是【另一具 ARX 机体某一次】的 24 组读数,
//!    冻成常数当"这台相机"。驱动里不许含有任何机体的任何参数(owner 2026-08-19 死命令);
//!    相机由这具身体自标定时看着自己的手当场量(插头里的 `全相机`,`point_gen::fit_full`),
//!    结果存进标定文件,任务时读回。
//! ② **尺度全部改成参数**(`尺` 结构)—— 钳口张开 / 工具长 / 可达 / 探针幅度,全是量出来的。
//! ③ **列轮换接上量出来的 `tool_axis_column`** —— 原来那份按 X5 写死"第 0 列 = 工具轴",
//!    Franka 的法兰约定不同,直接用就是把爪子再歪一次 90°(`v_head.mp4` 那类失败)。
//!    哪一列是工具轴,标定本来就量了,轮换按它来。


/// 这具身体的长度尺度 —— **全部量出来的,一个都不许有默认值。**
#[derive(Copy, Clone, Debug)]
pub struct 尺 {
    /// 钳口能张多开(标定 `gripper_span`,米)。
    pub 张开: f64,
    /// 工具尖到法兰(标定 `tool_offset`,米)。
    pub 工具长: f64,
    /// 可达带(标定 `reach`,米):内 / 外。
    pub 可达内: f64,
    pub 可达: f64,
    /// 接触阈是在多大命令上量的(标定旁注 `probed_at_command_m`,米)。
    pub 探幅: f64,
    /// 法兰旋转阵的哪一列是工具轴(标定 `tool_axis_column`,0/1/2)。
    pub 工具列: usize,
}

/// 链条断在哪 —— **点名**,不静默。
#[derive(Debug)]
pub enum NoGrasp {
    没圈出物体(String),
    点太少(usize),
    没有候选(String),
    交不出接触集(String),
    出不了航点(String),
}

/// **一帧:眼指的那一点 + 深度图 → 抓取候选 → 航点。只算不动手。**
#[allow(clippy::too_many_arguments)]
#[allow(clippy::too_many_arguments)]
pub fn 算一把(
    eye: &point_gen::Eye,
    depth: &[f64],
    w: usize,
    h: usize,
    at_px: point_gen::Px,
    span: f64,
    彩图: Option<&[u8]>,
    mu: f64,
    // 圈物体那道闸的宽容 —— 由眼自己问两次的分歧定,不是写死的。
    宽容: f64,
    朝我: [f64; 3],
    // 🔴 这一集**已经试过而且失败了**的下手点。重试要【独立】才有效。
    试过: &[[f64; 3]],
    // 🔴 这具身体的全部长度尺度 —— 量出来的,由调用方从标定里读了递进来。
    r: &尺,
) -> Result<(usize, usize, f64, [f64; 3], [f64; 4]), NoGrasp> {
    // ① 圈出物体:**锚在眼指的那一点上**,不对全画面用规则
    //(LAB:全局规则那次掩膜占了全帧 72%)
    let mask = point_gen::mask_around(eye, depth, w, h, at_px, span, 宽容)
        .map_err(|e| NoGrasp::没圈出物体(format!("{e:?}")))?;
    let 圈住 = mask.iter().filter(|b| **b).count();
    // 🔴 **第一次走通必须渲图去看** —— 仓规:*"first success:渲终帧,确认它【看起来】像成功,
    // 而不是一个指标上的技术性通过"*。这里把**圈中的像素涂红**、**眼指的那点画个十字**,
    // 落一张 BMP。数字骗得了人,图骗不了。
    if let Ok(dir) = std::env::var("BL_DUMP") {
        if let Some(rgb) = 彩图 {
            let _ = std::fs::create_dir_all(&dir);
            let mut v = rgb.to_vec();
            for (i, on) in mask.iter().enumerate() {
                if *on && i * 3 + 2 < v.len() {
                    v[i * 3] = 255;
                    v[i * 3 + 1] = v[i * 3 + 1] / 3;
                    v[i * 3 + 2] = v[i * 3 + 2] / 3;
                }
            }
            let (cx, cy) = (at_px[0] as i64, at_px[1] as i64);
            for d in -12i64..=12 {
                for (x, y) in [(cx + d, cy), (cx, cy + d)] {
                    if x >= 0 && y >= 0 && (x as usize) < w && (y as usize) < h {
                        let i = (y as usize * w + x as usize) * 3;
                        if i + 2 < v.len() {
                            v[i] = 0;
                            v[i + 1] = 255;
                            v[i + 2] = 0;
                        }
                    }
                }
            }
            let _ = std::fs::write(format!("{dir}/mask.bmp"), bmp24(&v, w, h));
            println!("[链] 渲图落盘 ⇒ {dir}/mask.bmp(红=圈中的像素,绿十字=眼指的点)");
        }
    }
    // 🔴🔴 **桌面要用【整幅图】估,不能只在掩膜里估。**
    // 实测(2026-08-17 夜):掩膜整块落在手臂上时,"桌面"被算成 0.97/1.03/1.05
    // (真桌面 ~0.74),而厚度/腰/指尖高度**全都照常算得出来**,一路放行。
    // ⇒ 整幅图里绝大多数像素是桌面,取中位数即可,鲁棒且零假设。
    // 这条同时给"作废到顶后的退让"一个**底线**:退让可以放宽挑法,但不许接受
    // 一个高出桌面 25 cm 的点 —— 那不是桌上的东西。
    let 桌面估 = {
        let 全掩: Vec<bool> = vec![true; w * h];
        let 稀 = point_gen::from_depth(eye, depth, &全掩, w, h);
        let mut zs: Vec<f64> = 稀.iter().step_by(37).map(|p| p.z).collect();
        if zs.is_empty() {
            None
        } else {
            zs.sort_by(|a, b| a.partial_cmp(b).unwrap());
            Some(zs[zs.len() / 2])
        }
    };
    let 本视角 = point_gen::from_depth(eye, depth, &mask, w, h);
    // 把别的视角里**落在同一处**的点收进来。判据不带任何倍数:
    // 物体是一个连着的东西,**没看见的那一半离看见的那一半不会超过这个物体自己的半径**。
    // 半径由视角 0 自己量出来(点云到质心的最大距离),所以这条判据是自缩放的。
    let 全 = {
        println!("[链] 🔴 **只有一个视角** —— 背面没看过。下游拿到的接触集是【从一面算出来的】,");
        println!("[链]    而它和多视角算出来的长得一模一样。要它更可信,就再看一眼(移一下 / 换台相机)。");
        本视角
    };
    // 🔴 **减掉支撑面 —— g5 那次假成功就死在没减。**
    // 相机斜着看时,圈里的桌面自带 60 mm 高差,深度筛子把整片桌面当成了物体,
    // 掩膜是个规整的圆盘(渲图抓出来的)。桌面在三维里是一张**平面**,物体**凸出于它**。
    // 支撑面容差 = 十分之一个钳口(无量纲比例)。
    let (pts, 法向, 面上) = point_gen::drop_support_plane(&全, 0.1 * r.张开);
    println!(
        "[链] 减支撑面:{} 点里 {} 在面上(法向 {:?})⇒ 剩 {}",
        全.len(), 面上, 法向.map(|v| (v * 100.0).round() / 100.0), pts.len()
    );
    if pts.len() < 8 {
        return Err(NoGrasp::点太少(pts.len()));
    }
    // 🔴🔴 **圈里没有支撑面时必须【拒绝】,不许拿"最低点"当桌面。**
    // 实测(2026-08-17 夜):眼指的那块整个悬在高处(圈到自己的手臂)时,
    // "桌面"被算成 **1.0375 / 1.0047**(真桌面 ~0.74,高出 26–30 cm),
    // 而厚度/腰部/指尖高度**全都照常算得出来**,一路流到下游 —— 又一个静默出错。
    // ⇒ 判据用**拟合本身**说话:支撑面拟合不出足够大的一片,就是这一圈里没有桌面。
    //   平面拟合会不成立,而"最低点"永远编得出一个数 —— 这就是区别。
    // 🔴 **支撑面还必须大致【水平】** —— 只查"够不够大"挡不住手臂的平面:
    // 实测(2026-08-17 夜)有一炮在面上的点够多、闸没响,而"桌面"算成 **0.9717**
    // (真桌面 ~0.74)、厚度算成 78.4 mm。⇒ 桌子是水平的,手臂的侧面不是。
    // 重力方向对任何机器人都是已知的,所以这条判据是**通用**的,不是给这个 benchmark 打补丁。
    // 🔴🔴 **闸不许把自己饿死** —— 今晚第三次栽在这上面。
    // 实测:法向 z=0.55 被判"不是桌子"而**每帧都拒**,手停在第 1 步一动不动、
    // 目标永远定不下来。前两次同型:够得着半径筛光 748 次候选 · 限幅让驱动 panic。
    // ⇒ 闸的职责是**拒绝坏目标 + 让出补救路径**,不是拒绝到什么都不做。
    //   阈值放宽到 0.6(仍能挡住竖直的臂面 z≈0),并**把实际法向打出来**,
    //   让"为什么放行/为什么拒"永远看得见。
    // 保护全拆(owner 2026-08-17):6 道闸,6 次把自己的链搞死,0 次挡住真问题 ⇒ 只报数,不否决。
    // 0.60 ≈ cos 53°:法向偏离竖直超过这个角就不算支撑面。**无量纲**,不描述任何身体。
    if 法向[2].abs() < 0.60 {
        println!("[链] ⚠️ 面不太水平(法向 z={:.2})—— 照常往下走", 法向[2]);
    }
    let 面占比 = 面上 as f64 / 全.len().max(1) as f64;
    // 占比是**比例**,无量纲:一团点里不到四分之一落在那张平面上,就不认为找到了支撑面。
    if 面占比 < 0.25 {
        println!("[链] ⚠️ 这一圈里支撑面只占 {:.0}% —— 照常往下走", 面占比 * 100.0);
    }
    // 🔴🔴 **把"明显不是桌上物体"的高点滤掉 —— 那是自己的胳膊。**(2026-08-17 实拍)
    // 物体落在手臂旁边时,掩膜会连一截**手臂本体**一起圈进来:实测下手点 z=**1.02/1.03**
    // (桌面 ~0.75,高出 27 cm),下手宽 **5.3/7.2 mm**,而候选条数/航点步数**全部正常**。
    // ⇒ 以圈内最低点(桌面)为基准,**高出 12 cm 以上的一律不是这一把要抓的东西**。
    // ⚠️ 先试过"让手臂让开"——**方向是反的**:俯视相机下手臂降低反而压在物体上方,更挡。
    let zfloor = 全.iter().fold(f64::MAX, |a, p| a.min(p.z));
    let before = pts.len();
    let 换: Vec<contact_gen::P3> = pts
        .iter()
        // 高出桌面 0.7 个可达半径(无量纲)以上的多半是自己的胳膊。
        .filter(|p| p.z <= zfloor + 0.7 * r.可达)
        .map(|p| contact_gen::P3 { x: p.x, y: p.y, z: p.z })
        .collect();
    if 换.len() < before {
        println!("[链] 滤高点:{} 个点里 {} 个比桌面高 12 cm 以上(多半是自己的胳膊)⇒ 剩 {}",
            before, before - 换.len(), 换.len());
    }
    if 换.len() < 8 {
        return Err(NoGrasp::点太少(换.len()));
    }
    let (zlo, zhi) = 换.iter().fold((f64::MAX, f64::MIN), |(a, b), p| (a.min(p.z), b.max(p.z)));
    println!(
        "[链] 圈住 {圈住} 像素 ⇒ {} 个三维点 · 高度 {:.4}..{:.4}(跨 {:.1} mm)",
        pts.len(), zlo, zhi, (zhi - zlo) * 1000.0
    );
    let body = contact_gen::Body {
        jaw: contact_gen::JawSpan::Measured(r.张开),
        reach_lo: r.可达内,
        reach_hi: r.可达,
        base_x: 0.0,
        base_y: 0.0,
    };
    let cs = contact_gen::candidates(&换, &body, zlo, {
            // 🔴🔴 **切层的四个尺寸全部由【量出来的钳口张开】给,不再用 `Grid::default()`。**
            // 那份 default 是 `jaw_h_m: 0.03 · min_above_m: 0.005 · finger_w_m: 0.02 · gap_m: 0.01`
            // —— 四个以米写死的爪子几何。换一具爪子(Franka 的开口与 ARX 差一倍)它们全错,
            // 而错的方式是**安静的**:切片厚度与爪面无关 ⇒ 量出来的"这一段有多宽"说的是
            // 一片纸那么薄的横截面。档案实测过这件事:`段宽 ÷ 爪停读数` 全距 **0.0011–0.7516,近 700 倍**。
            // 🔴 `jaw_h_m`(爪面有多高)**仍然是一个没量到的身体量**,这里按张开的比例给 ——
            // 债照记在 `contact-gen` 那个字段的注释里,只是不再是一个与身体无关的绝对值。
            let 张 = r.张开;
            contact_gen::Grid {
                jaw_h_m: 0.8 * 张,
                min_above_m: 0.14 * 张,
                finger_w_m: 0.55 * 张,
                gap_m: 0.27 * 张,
                ..contact_gen::Grid::default()
            }
        })
        .map_err(|e| NoGrasp::没有候选(format!("{e:?}")))?;
    let 静 = contact_set::Twist::still([0.0; 3]);
    // 🔴🔴 **斜着下手,把"够不着"当【硬约束】用,而不是硬撬那几厘米。**
    //
    // 爪子笔直往下扎时,手腕必须**正好悬在物体正上方**;往身体那侧倾 θ,
    // 手腕就能**退后 `0.1451·sinθ`** 而爪尖仍落在同一点(θ=30° ⇒ **7.3 cm**)。
    // 实测差的是 2.6–3.9 cm ⇒ 余量两倍。
    //
    // ⚠️ **倾必须绕【钳口连线】倾**,不然两根手指一高一低(宽 40 mm、θ=30° ⇒ 差 20 mm),
    // 低的那根会先撞桌子。⇒ 只有当钳口连线**大致垂直于**"要往哪个方向多够一点"时才倾;
    // 否则倾了也没有收益(收益 ∝ |p̂·ĥ|),那就老实不倾。
    //
    // 🔴 **不重排候选** —— 档案:*强制候选 1 = 7 赢 25 输;候选 3 = 0 赢 57 输*
    // ⇒「最窄边优先」的默认排序是对的。这里只在默认顺序里**跳过倾不了的**,不换判据排序。
    // 🔴🔴 **先问"这条胳膊够得着吗",再挑下手点 —— 顺序不能反。**
    //
    // 实测(2026-08-17):程序先挑好一个下手点,伸到一半才发现够不着,然后杵在原地
    // 167 步。而每一帧其实算出了 **400 多条候选**,只用第一条、其余全扔 ——
    // **里面很可能就有够得着的那条**。
    //
    // "能伸多远"是**量出来的身体常数**,不是拍的:手从原位实际走出 **0.400 m**
    // (原位 (0.3005,-0.3523,0.9215) → 走到 (0.2280,0.0373,0.9800) 后逐轴探针确认
    // 只有"往前"实挪 0.0 mm、对照"往上"挪满 29.9 mm ⇒ 是够不着,不是通道坏)。
    // 🔴 **不许有 env 兜底,也不许有默认值** —— 这个半径是标定里 `reach` 那一格量出来的
    // (机器人自己伸出去探到头),由调用方递进来。递不到 = 没量过 = 拒绝干活。
    let 够得着 = r.可达;
    let mut 够不着的 = 0usize;
    let mut 最近 = f64::MAX;
    let mut 兜底: Option<contact_set::ContactSet> = None;
    let mut 选中: Option<(contact_set::ContactSet, f64, [f64; 3])> = None;
    for c in cs.iter() {
        // 接触点容差 = 二十分之一个钳口(无量纲比例)。
        let Ok(s) = c.to_set(mu, 静, 0.05 * r.张开) else { continue };
        if s.points.len() < 2 {
            continue;
        }
        let 中 = [
            (s.points[0].at[0] + s.points[1].at[0]) / 2.0,
            (s.points[0].at[1] + s.points[1].at[1]) / 2.0,
            (s.points[0].at[2] + s.points[1].at[2]) / 2.0,
        ];
        // 🔴 够不着的候选**当场跳过**,不进下游。
        // ⚠️ **但兜底要在筛之前存** —— 实测(2026-08-17):我把半径取成"某次卡住时的距离
        // 0.400 m",而同一条胳膊**实际够到过 0.474 m**(那一集贴上到位差 6.1 mm)。
        // 结果这道闸 **748 次把候选全筛光**,链条断在"交不出接触集"。
        // **一道会把自己饿死的闸,比没有闸更糟** ⇒ 筛空了自动放行并在日志里说清楚。
        // 🔴 **绕开这一集试过的点。** "多远算同一个点"不拍一个数:用量出来的钳口跨度 ——
        // 两个下手点离得比钳口还近,爪子合下去碰的就是同一片,那不是一次独立的重试。
        if 试过.iter().any(|t| {
            ((t[0] - 中[0]).powi(2) + (t[1] - 中[1]).powi(2) + (t[2] - 中[2]).powi(2)).sqrt() < r.张开
        }) {
            continue;
        }
        兜底.get_or_insert(s.clone());
        let r = ((朝我[0] - 中[0]).powi(2) + (朝我[1] - 中[1]).powi(2) + (朝我[2] - 中[2]).powi(2)).sqrt();
        if r > 够得着 {
            够不着的 += 1;
        }
        // ĥ:从物体指向"我现在在哪"的水平方向 = 要往哪边退才够得着
        let mut h = [朝我[0] - 中[0], 朝我[1] - 中[1], 0.0];
        let hl = (h[0] * h[0] + h[1] * h[1]).sqrt();
        if hl < 1e-6 {
            兜底.get_or_insert(s);
            continue;
        }
        h = [h[0] / hl, h[1] / hl, 0.0];
        // ĵ:钳口连线(水平分量)
        let mut j = [
            s.points[1].at[0] - s.points[0].at[0],
            s.points[1].at[1] - s.points[0].at[1],
            0.0,
        ];
        let jl = (j[0] * j[0] + j[1] * j[1]).sqrt();
        if jl < 1e-6 {
            兜底.get_or_insert(s);
            continue;
        }
        j = [j[0] / jl, j[1] / jl, 0.0];
        // p̂ = ĵ × ẑ,水平且垂直于钳口连线 —— 倾只能往这个方向倾
        let p = [j[1], -j[0], 0.0];
        let ph = p[0] * h[0] + p[1] * h[1];
        // 🔴🔴 **在够得着的候选里,挑【离身体最近】的那个。**
        // 实测(2026-08-17 夜):够不着是这条链现在唯一的阻塞,而它每次只差几厘米
        // (23/39/47 mm)。同一个物体上的候选彼此相差可达几厘米 —— **挑近的那个
        // 正好买到这个量级**。
        // ⚠️ 这不是档案判死的"改下手点排序"(那次是**强制固定序号**:候选 1 = 7 赢 25 输、
        // 候选 3 = 0 赢 57 输)。这里用的是 `DRIVER_GOAL:140` 明写认可的那条:
        // *量出来的是【硬】约束(这条胳膊就是够不到),硬约束能砍搜索空间*。
        // 0.6 = 倾的收益系数下限(cos 夹角,无量纲)—— 低于它,倾了也退不了多少。
        if ph.abs() > 0.6 && r < 最近 {
            最近 = r;
            选中 = Some((s, ph, p));
        }
    }
    println!("[链] 够得着筛:半径 {:.3} m ⇒ 扔掉 {} 条;选中的那条离手 {:.3} m", 够得着, 够不着的, 最近);
    let (mut set, 倾) = match 选中 {
        Some((s, ph, p)) => {
            // 🔴🔴 **倾多少度是【算】出来的,不是人拍的。**(owner 2026-08-17:全部写死的常数删掉)
            //
            // 之前 `LINK_TILT_DEG=45` 是我拍的,而视频当场证明它就是那个卡死的东西:
            // 手腕被要求歪 45°,整条臂扭到工作空间边缘,指尖悬在桌面上方 **13 cm** 再也下不去,
            // 从第 41 步到第 141 步位置**逐位相同**(`run_gp8` 头相机视频,2026-08-17)。
            //
            // 倾的**唯一用处**是让手腕退后 `工具长度·sinθ`,从而把够不着的那一段补上。
            // ⇒ 需要退多少是**算得出来**的:`缺 = 这一把离手多远 − 量出来的够得着上界`。
            //   缺多少就倾多少,`θ = asin(缺 / 工具长度)`;**够得着就一点都不倾**(θ=0)。
            // 两个输入全是机器人量自己量到的:`reach`(伸出去探到头)· `tool_offset`(工具长度)。
            let 缺 = (最近 - 够得着).max(0.0);
            let 收益系数 = ph.abs().max(1e-6);
            let θ = (缺 / (r.工具长 * 收益系数)).clamp(0.0, 1.0).asin();
            let sgn = if ph > 0.0 { -1.0 } else { 1.0 };
            let (st, ct) = (θ.sin(), θ.cos());
            let a = [sgn * p[0] * st, sgn * p[1] * st, -ct];
            let mut s = s;
            s.approach = Some(a);
            println!("[链] 倾角是算的:离手 {:.3} m · 够得着上界 {:.3} m ⇒ 缺 {:.1} mm ⇒ 倾 {:.1}°",
                最近, 够得着, 缺 * 1000.0, θ.to_degrees());
            (s, r.工具长 * st * ph.abs())
        }
        None => (
            兜底.ok_or_else(|| NoGrasp::交不出接触集("没有一条候选过得了摩擦锥".into()))?,
            0.0,
        ),
    };
    let _ = &mut set;
    println!(
        "[链] 下手姿态:倾 {:.0}° ⇒ 手腕能退后 {:.1} mm(0 = 这一把钳口方向倾了没收益,老实竖着下)",
        if 倾 > 0.0 { (倾 / (r.工具长).max(1e-9)).clamp(0.0, 1.0).asin().to_degrees() } else { 0.0 },
        倾 * 1000.0
    );
    let 宽 = contact_set::norm([
        set.points[1].at[0] - set.points[0].at[0],
        set.points[1].at[1] - set.points[0].at[1],
        set.points[1].at[2] - set.points[0].at[2],
    ]);
    let steps = contact_exec::plan::steps(
        &set,
        // 悬停 = 一个钳口;重复步长 = 钳口的 3%(无量纲比例)。
        &contact_exec::plan::Body { standoff_m: r.张开, repeat_m: 0.03 * r.张开 },
        false,
        1,
    )
    .map_err(|e| NoGrasp::出不了航点(format!("{e:?}")))?;
    println!(
        "[链] 候选 {} 条 ⇒ 下手宽 {:.1} mm ⇒ 航点 {} 步(贴上那步第一个接触点 {:?})",
        cs.len(), 宽 * 1000.0, steps.len(),
        steps[1].at[0].map(|v| (v * 1e4).round() / 1e4)
    );
    // 工具尖要到的地方 = 两个接触点的中点(贴上那一步)
    let a = steps[1].at[0];
    let b = steps[1].at[1];
    let q = 换成机器人的约定(&steps[1].quat[0], r.工具列);
    println!(
        "[链] 手腕:接触集要工具轴 {:?} · 钳口张开方向 {:?}",
        列(&q, 0).map(|v| (v * 100.0).round() / 100.0),
        列(&q, 1).map(|v| (v * 100.0).round() / 100.0)
    );
    // 🔴🔴 **手指要停在物体的【腰】上,不是顶面上。**
    // 深度相机只看得见**顶面** ⇒ 下手点天然落在顶面高度;而平物体只有几毫米厚,
    // 在顶面高度合拢 = **在物体上方合空**(2026-08-17 三张图实证:瞄到 1 px 仍抬起空气)。
    //
    // ⚠️ **这不是那条判死的「压下去测高度」**(`DRIVER_GOAL:437` 配对实证:刚性下压把物体
    // 推走,带探针 夹到=False / 去掉 夹到=True)。这里**一次都不碰它** —— 顶面由深度给、
    // 桌面由支撑面拟合给,两个都是**量出来的面**,在它们之间取一个高度。这正是
    // `DRIVER_GOAL:438` 点名"两处要它、从没建过"的那条**不接触测高**通道,
    // 而这条链每一帧其实早就把两个面都算出来了。
    // ⚠️ 也**不是**「把顶面拉到支撑面」那个假设(`DRIVER_GOAL:360`:马克杯把手底下是空的,
    // 拉出来是一堵不存在的墙)—— 我们**不臆造中间的材料**,只在两个看得见的面之间选高度。
    let 顶面z = (a[2] + b[2]) / 2.0;
    let 厚 = (顶面z - zfloor).max(0.0);
    // ⚠️ **下限不是 2 mm** —— 实测(2026-08-17)连着两集「没贴上」:悬停准到 **2.2 mm**,
    // 而往下压那 6 cm 压不下去、卡 146/161 步。假设:这台仿真的运动规划**带碰撞检查**,
    // 指尖压到贴桌面时**整条姿态被拒**,表现就是"命令发了、手不动"(与够不着同形)。
    // ⇒ 下限抬到 `LINK_TIPMIN_M`(默认 8 mm),压得下去就说明是碰撞,不是够不着。
    // 🔴🔴 **正解:指尖目标 = 物体腰部 + 【量出来的】工具尖偏置。**
    // 固定下限那条路有内在矛盾(2026-08-17 夜逐档实测):
    //   8 mm ⇒ 真指尖插到桌下,下降被拒 · 45 mm ⇒ 贴着桌面把布压住,抬起来是空的
    //   60 mm ⇒ 夹的位置对了,但**悬停和抬升两个目标都被抬高** ⇒ 一集悬停差 50 mm 够不着、
    //           一集只抬到 78 mm。**高了够不着,低了夹不住。**
    // 根因:程序里的"工具尖"其实在真指尖**上方约 40 mm**(区间由 8 失败 / 45 通过夹出)。
    // ⇒ 把这段偏置**显式加到腰部**上,薄物体自然低、厚物体自然高,
    //   **不会为了迁就偏置把整个姿态抬高**。这也把"我拍的参数"换回"身体量出来的量"。
    // 🔴🔴 **订正:那 40 mm 不是"高度补偿",是【工具尖到法兰的距离】本来就长 40 mm。**
    // 我原来把它当纯竖直加进高度 ⇒ **倾角 45° 时漏掉了水平那 28 mm**,
    // 于是爪子擦着物体边上合下去(2026-08-17 夜腕相机实拍:两指之间是空桌面,
    // 扑克牌在左、耳机盒在右)。⇒ 偏置必须**沿工具轴**加,即并进 `main.rs` 的工具长度里,
    // 这一层只给**物体腰部**这个纯几何量。
    // 指尖高度夹在钳口的 5%..140%(无量纲比例)之间:太低插桌,太高合空。
    let 指尖z = zfloor + (厚 * 0.5).clamp(0.05 * r.张开, 1.4 * r.张开);
    let 腰 = 指尖z;
    if let Some(t) = 桌面估 {
                // 1.5 个可达半径(无量纲)—— 只决定打不打这行警告。
    if 指尖z - t > 1.5 * r.可达 {
            println!("[链] ⚠️ 下手点比整帧估的桌面({:.3})高 {:.0} cm —— 照常往下走",
                t, (指尖z - t) * 100.0);
        }
    }
    let 偏置 = 0.0f64;
    println!(
        "[链] 不接触测高:桌面 {:.4} · 顶面 {:.4} ⇒ 厚 {:.1} mm ⇒ 腰 {:.4} + 偏置 {:.0} mm ⇒ 命令指尖 {:.4}",
        zfloor, 顶面z, 厚 * 1000.0, 腰, 偏置 * 1000.0, 指尖z
    );
    Ok((
        cs.len(),
        steps.len(),
        宽,
        [(a[0] + b[0]) / 2.0, (a[1] + b[1]) / 2.0, 指尖z],
        q,
    ))
}

/// 四元数 `(w,x,y,z)` → 旋转阵的第 `c` 列。
pub fn 列(q: &[f64; 4], c: usize) -> [f64; 3] {
    let m = 阵(q);
    [m[0][c], m[1][c], m[2][c]]
}

fn 阵(q: &[f64; 4]) -> [[f64; 3]; 3] {
    let (w, x, y, z) = (q[0], q[1], q[2], q[3]);
    [
        [1.0 - 2.0 * (y * y + z * z), 2.0 * (x * y - z * w), 2.0 * (x * z + y * w)],
        [2.0 * (x * y + z * w), 1.0 - 2.0 * (x * x + z * z), 2.0 * (y * z - x * w)],
        [2.0 * (x * z - y * w), 2.0 * (y * z + x * w), 1.0 - 2.0 * (x * x + y * y)],
    ]
}

/// 🔴🔴 **两边对"哪一列是什么"的约定不一样,直接喂过去爪子会歪 90°。**
///
/// - **机器人**:第 0 列 = 工具轴(`debt.rs` 原文 `tcp = flange + 0.145 × R[:,0]`),
///   第 1 列 = 钳口张开方向(`WRIST_DOWN_WXYZ` 的注释)。
/// - **接触集**(`plan::frame_from`):第 2 列 = 进场/工具轴,第 0 列 = 开合轴。
///
/// ⇒ 列做一次**轮换** `(x,y,z) → (z,x,y)`。轮换是偶置换,行列式仍是 +1,不会把
/// 右手系翻成左手系(翻了的话爪子会镜像张开,而没有任何一环会不一致)。
///
/// 这一格是档案点名的**债**:*"真正缺的那一槽是钳口自转"* —— 平躺的薄物体,
/// 钳口差 90° 就是去夹最宽那一边。接触集本来就算好了它,以前被写死的常数盖掉了。
pub fn 换成机器人的约定(q: &[f64; 4], 工具列: usize) -> [f64; 4] {
    let m = 阵(q);
    // 🔴🔴 **轮换按【量出来的】工具轴列号来,不按某一具机体写死。**
    // 接触集(`plan::frame_from`)的约定:第 2 列 = 工具轴,第 0 列 = 开合轴。
    // 这具机器人哪一列是工具轴 = 标定 `tool_axis_column`(绕每列转腕,弧最小的那列)。
    // 映射:接触集第 2 列 → 机器人第 τ 列;第 0 列 → 第 (τ+1)%3 列;第 1 列 → 第 (τ+2)%3 列。
    // τ=0 时正好还原老 X5 那份写死的轮换(`(x,y,z)→(z,x,y)`);τ=2 时是恒等。
    // 三种都是偶置换,不翻手系。
    // ⚠️ 记一笔债:开合轴放在 (τ+1)%3 是**约定不是测量** —— "哪一列是钳口张开方向"
    // 目前没有一格在量它;放错的病相是爪子歪 90°。真修法是给它自己的一格。
    let τ = 工具列 % 3;
    let src = [2usize, 0, 1];
    let mut r = [[0.0f64; 3]; 3];
    for k in 0..3 {
        let dst = (τ + k) % 3;
        for i in 0..3 {
            r[i][dst] = m[i][src[k]];
        }
    }
    // 下面的 0.25 是旋转阵→四元数重建公式里的数学常数,无量纲。
    let tr = r[0][0] + r[1][1] + r[2][2];
    let q = if tr > 0.0 {
        let s = (tr + 1.0).sqrt() * 2.0;
        [0.25 * s, (r[2][1] - r[1][2]) / s, (r[0][2] - r[2][0]) / s, (r[1][0] - r[0][1]) / s]
    } else if r[0][0] > r[1][1] && r[0][0] > r[2][2] {
        let s = (1.0 + r[0][0] - r[1][1] - r[2][2]).sqrt() * 2.0;
        [(r[2][1] - r[1][2]) / s, 0.25 * s, (r[0][1] + r[1][0]) / s, (r[0][2] + r[2][0]) / s]
    } else if r[1][1] > r[2][2] {
        let s = (1.0 + r[1][1] - r[0][0] - r[2][2]).sqrt() * 2.0;
        [(r[0][2] - r[2][0]) / s, (r[0][1] + r[1][0]) / s, 0.25 * s, (r[1][2] + r[2][1]) / s]
    } else {
        let s = (1.0 + r[2][2] - r[0][0] - r[1][1]).sqrt() * 2.0;
        [(r[1][0] - r[0][1]) / s, (r[0][2] + r[2][0]) / s, (r[1][2] + r[2][1]) / s, 0.25 * s]
    };
    let n = (q[0] * q[0] + q[1] * q[1] + q[2] * q[2] + q[3] * q[3]).sqrt();
    [q[0] / n, q[1] / n, q[2] / n, q[3] / n]
}

